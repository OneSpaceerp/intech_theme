#!/usr/bin/env python3
"""Draw the backdrop artwork in `intech_theme/public/images/backdrops/`.

    circuit.svg         the logo's circuit traces, drawn large, for /desk and the login page
    circuit-corner.svg  a small cluster of them, for the foot of the Gradient sidebar
    waves.svg           three layered waves in the brand blues

Seeded, so a re-run draws the same picture. Standard library only:

    python tools/build_backdrops.py
"""

from __future__ import annotations

import math
import random
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "intech_theme" / "public" / "images" / "backdrops"

# The logo's trace colours, light to dark, and the tile's steel.
BLUES = ["#1E90D2", "#2472AE", "#245490", "#7898B8", "#1E90D2", "#2472AE"]


def traces(origin, count, length_range, angle, bend, stroke, node_r, spread, opacity_range, rng):
	"""A fan of traces like the logo's: a straight run, one bend, a ring at the end."""
	out = []
	ox, oy = origin
	a = math.radians(angle)
	b = math.radians(angle + bend)
	for i in range(count):
		offset = (i - count / 2) * spread
		sx = ox + offset * math.cos(a + math.pi / 2)
		sy = oy + offset * math.sin(a + math.pi / 2)
		first = rng.uniform(*length_range)
		second = rng.uniform(first * 0.25, first * 0.6)
		mx, my = sx + first * math.cos(a), sy + first * math.sin(a)
		ex, ey = mx + second * math.cos(b), my + second * math.sin(b)
		color = BLUES[i % len(BLUES)]
		opacity = rng.uniform(*opacity_range)
		out.append(
			f'<g stroke="{color}" stroke-opacity="{opacity:.2f}" fill="none" stroke-width="{stroke}" '
			'stroke-linecap="round" stroke-linejoin="round">'
			f'<path d="M{sx:.1f} {sy:.1f}L{mx:.1f} {my:.1f}L{ex:.1f} {ey:.1f}"/>'
			f'<circle cx="{ex:.1f}" cy="{ey:.1f}" r="{node_r}"/></g>'
		)
	return "\n".join(out)


def wave(y, amplitude, length, phase):
	points = [(x, y + amplitude * math.sin((x / length) * 2 * math.pi + phase)) for x in range(0, 1601, 40)]
	return (
		f"M0 1000L{points[0][0]} {points[0][1]:.1f}"
		+ "".join(f"L{x} {py:.1f}" for x, py in points[1:])
		+ "L1600 1000Z"
	)


def main() -> int:
	OUT.mkdir(parents=True, exist_ok=True)
	rng = random.Random(7)

	body = traces((1700, 1150), 16, (380, 720), 212, 38, 3, 9, 46, (0.22, 0.55), rng)
	body += traces((-260, -220), 8, (260, 420), 28, 40, 2.2, 6, 44, (0.08, 0.2), rng)
	(OUT / "circuit.svg").write_text(
		'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1600 1000" preserveAspectRatio="xMidYMid slice">\n'
		"<!-- In Tech circuit backdrop. Generated by tools/build_backdrops.py; edit that, not this. -->\n"
		f"{body}\n"
		'<g fill="#1E90D2" fill-opacity=".5"><circle cx="1180" cy="210" r="4"/>'
		'<circle cx="420" cy="820" r="3"/><circle cx="1460" cy="540" r="3"/></g>\n</svg>',
		encoding="utf-8",
	)

	corner = traces((330, 300), 7, (150, 240), 215, 40, 3, 7, 24, (0.6, 1.0), rng).replace(
		'stroke="#7898B8"', 'stroke="#C3DFEC"'
	)
	(OUT / "circuit-corner.svg").write_text(
		f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 300 260">\n{corner}\n</svg>', encoding="utf-8"
	)

	(OUT / "waves.svg").write_text(
		'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1600 1000" preserveAspectRatio="none">\n'
		"<defs>"
		'<linearGradient id="w1" x1="0" y1="0" x2="1" y2="0"><stop offset="0" stop-color="#1E90D2"/>'
		'<stop offset="1" stop-color="#245490"/></linearGradient>'
		'<linearGradient id="w2" x1="0" y1="0" x2="1" y2="0"><stop offset="0" stop-color="#2472AE"/>'
		'<stop offset="1" stop-color="#1E2448"/></linearGradient>'
		"</defs>\n"
		f'<path d="{wave(690, 34, 900, 0.4)}" fill="#ABC7DA" fill-opacity=".35"/>\n'
		f'<path d="{wave(760, 42, 1100, 1.8)}" fill="url(#w1)" fill-opacity=".38"/>\n'
		f'<path d="{wave(840, 30, 760, 3.1)}" fill="url(#w2)" fill-opacity=".55"/>\n</svg>',
		encoding="utf-8",
	)
	print(f"wrote 3 backdrops to {OUT}")
	return 0


if __name__ == "__main__":
	raise SystemExit(main())
